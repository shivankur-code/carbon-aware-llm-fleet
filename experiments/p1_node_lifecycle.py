"""Phase-1 sanity study: lifecycle carbon per unit of delivered work for ONE node of each SKU.

Not the fleet MILP. It answers a narrower question that the MILP will build on:
per unit of delivered LLM work over a fixed service life, how much greener is a
reused-component node, (a) ignoring failures, (b) counting failures, spares,
logistics and drained capacity?

Usage:  python experiments/p1_node_lifecycle.py [--years 6] [--util 0.6]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from carbonsched.carbon import node_quarter_carbon, purchase_embodied_kg  # noqa: E402
from carbonsched.grid import load_regions  # noqa: E402
from carbonsched.hardware import load_catalog  # noqa: E402
from carbonsched.params import parameters_table  # noqa: E402
from carbonsched.reliability import HOURS_PER_YEAR, QUARTER, QuarterReliability, node_reliability_table  # noqa: E402


def node_lifecycle(sku, region, n_q, util, tier, policy, with_failures):
    rel = node_reliability_table(sku.slots, n_q) if with_failures else [QuarterReliability() for _ in range(n_q)]
    emb = purchase_embodied_kg(sku, policy)
    op = spares = logi = work = lost = 0.0
    for q in range(n_q):
        c = node_quarter_carbon(sku, rel[q], region, q, util)
        op += c.operational_kg
        spares += c.spares_kg
        logi += c.logistics_kg
        up = 1.0 - rel[q].availability_loss
        work += sku.effective_throughput(tier) * util * HOURS_PER_YEAR * QUARTER * up
        lost += rel[q].availability_loss / n_q
    total = emb + op + spares + logi
    return dict(sku=sku.name, region=region.name, tier=tier, policy=policy, failures=with_failures,
                embodied_kg=emb, operational_kg=op, spares_kg=spares, logistics_kg=logi, total_kg=total,
                work=work, avail_loss=lost, g_per_work=1000 * total / work,
                failures_per_node=sum(r.total_failures for r in rel))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--years", type=float, default=6)
    ap.add_argument("--util", type=float, default=0.6)
    args = ap.parse_args()
    cat = load_catalog(ROOT / "configs")
    regions = load_regions(ROOT / "configs", cat.registry)
    n_q = int(args.years * 4)

    rows = [node_lifecycle(cat.skus[s], regions[r], n_q, args.util, t, p, f)
            for s in ("new_gpu", "green_gpu", "old_gpu") for r in regions for t in ("LC", "BATCH")
            for p in ("cutoff", "residual") for f in (False, True)]
    df = pd.DataFrame(rows)
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    df.to_csv(out / "p1_node_lifecycle.csv", index=False)

    piv = df[df.sku.isin(["new_gpu", "green_gpu"])].pivot_table(
        index=["region", "tier", "policy", "failures"], columns="sku", values="g_per_work")
    piv["saving"] = 100 * (1 - piv["green_gpu"] / piv["new_gpu"])
    s = piv["saving"].unstack("failures").rename(columns={False: "no_failures_%", True: "with_failures_%"})
    s["eroded_pp"] = s["no_failures_%"] - s["with_failures_%"]
    print("\nGreenSKU-style node vs new node: % saving in lifecycle gCO2e per unit work")
    print(s.round(2).to_string())
    s.round(3).to_csv(out / "p1_green_vs_new.csv")

    c = df[(df.failures) & (df.policy == "cutoff")].pivot_table(index=["region", "tier"], columns="sku", values="g_per_work")
    c["old_vs_new_%"] = 100 * (1 - c["old_gpu"] / c["new_gpu"])
    print("\nCascaded old node vs new node (failures counted, cutoff): % saving per unit work")
    print(c[["old_vs_new_%"]].round(1).to_string())
    c.round(3).to_csv(out / "p1_old_vs_new.csv")

    f = df[(df.failures) & (df.region == "mixed") & (df.tier == "LC") & (df.policy == "cutoff")]
    print("\nPer-node 6-yr breakdown (mixed grid, LC, cutoff), kgCO2e:")
    print(f[["sku", "embodied_kg", "operational_kg", "spares_kg", "logistics_kg", "avail_loss", "failures_per_node"]]
          .round(3).to_string(index=False))

    (ROOT / "paper" / "parameters.md").write_text(
        "# Model parameters\n\nGenerated by `experiments/p1_node_lifecycle.py` from `configs/`. "
        "`assumption` values are swept in sensitivity studies; `derived` values show their derivation.\n\n"
        + parameters_table(cat.registry))


if __name__ == "__main__":
    main()
